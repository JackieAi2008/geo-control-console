/* 知识库检索：关键词命中打分，≥2 分才命中（避免单字误命中）。
   返回 {answer} 或 null（未命中走 LLM） */
function kbSearch(q) {
  if (!q || q.length < 2) return null;
  const s = q.toLowerCase();
  let best = null, bestScore = 0;
  for (const item of CHAT_KB) {
    let score = 0;
    for (const kw of item.keywords) {
      if (s.includes(kw.toLowerCase())) score += kw.length >= 4 ? 2 : 1;
    }
    if (score > bestScore) { bestScore = score; best = item; }
  }
  return bestScore >= 2 ? { answer: best.answer } : null;
}
